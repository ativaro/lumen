"""Generate the Unicode 16 word/digit/wide ranges of src/unicode_data.rs, never from user data.

usage: python3 generate_unicode.py (a Python whose unicodedata is 16.0.0); the output is committed."""
from hashlib import sha256
from pathlib import Path
import unicodedata

assert unicodedata.unidata_version == '16.0.0', 'Use the qualified Python Unicode version.'


def scalars():
    return (chr(i) for i in range(0x110000) if not 0xD800 <= i <= 0xDFFF)


def ranges(predicate):
    result = []
    for ch in scalars():
        if predicate(ch):
            n = ord(ch)
            if result and result[-1][1] == n-1:
                result[-1][1] = n
            else:
                result.append([n, n])
    return ',\n'.join(f'    (0x{a:x}, 0x{b:x})' for a, b in result) + ','


# The crate's tests compare the Rust folding of every scalar with this digest.
digest = sha256()
for ch in scalars():
    digest.update(bytes([ch.isalnum() or ch == '_', ch.isdigit()]))
    for value in (ch.casefold(), unicodedata.normalize('NFC', ch), unicodedata.normalize('NFKC', ch).casefold()):
        encoded = value.encode()
        digest.update(len(encoded).to_bytes(2, 'little'))
        digest.update(encoded)
target = Path(__file__).resolve().parent / 'src/unicode_data.rs'
target.write_text(
    '// Generated by generate_unicode.py (native/memory of the Desktop repository) with Unicode 16.0.0.\n'
    '// Current Notes tag and memory search identity; no runtime version adapter.\n'
    '// Derived from the Unicode Character Database 16.0.0 (Unicode License V3).\n'
    '#[rustfmt::skip]\npub(super) const WORD: &[(u32,u32)] = &[\n' +
    ranges(lambda c: c.isalnum() or c == '_') + '\n];\n'
    '#[rustfmt::skip]\npub(super) const DIGIT: &[(u32,u32)] = &[\n' +
    ranges(str.isdigit) + '\n];\n'
    '#[rustfmt::skip]\npub(super) const WIDE: &[(u32,u32)] = &[\n' +
    ranges(lambda c: unicodedata.east_asian_width(c) in 'WF') + '\n];\n'
    f'#[cfg(test)]\npub(super) const SCALAR_DIGEST: &str =\n    "{digest.hexdigest()}";\n'
)
